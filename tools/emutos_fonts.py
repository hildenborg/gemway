#!/usr/bin/env python3
"""Convert EmuTOS fnt_st_*.c system font sources into src/gem/sysfonts.cpp.

The EmuTOS fonts are GPL-2.0-or-later (C) The EmuTOS development team.
Usage: tools/emutos_fonts.py fnt_st_6x6.c fnt_st_8x8.c fnt_st_8x16.c > src/gem/sysfonts.cpp
"""
import re, sys

def parse(path):
    src = open(path).read()
    m = re.search(r'dat_table\s*\[[^\]]*\]\s*=\s*\{(.*?)\};', src, re.S)
    words = [int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]+)', m.group(1))]
    fw = int(re.search(r'(\d+),\s*/\*\s*form_width', src).group(1))
    fh = int(re.search(r'(\d+),\s*/\*\s*form_height', src).group(1))
    cw = int(re.search(r'(\d+),\s*/\*\s*max_cell_width', src).group(1))
    top = int(re.search(r'(\d+),\s*/\*\s*top', src).group(1))
    data = bytearray()
    for w in words:
        data += bytes([(w >> 8) & 0xff, w & 0xff])  # dat_table is big-endian form data
    assert len(data) == fw * fh, (path, len(data), fw * fh)
    # Re-pack into one byte-row per glyph: glyph g row r -> bits of cell (cw <= 8)
    glyphs = []
    for g in range(256):
        rows = []
        for r in range(fh):
            v = 0
            for b in range(cw):
                bit = g * cw + b
                byte = data[r * fw + bit // 8]
                if byte & (0x80 >> (bit % 8)):
                    v |= 0x80 >> b
            rows.append(v)
        glyphs.append(rows)
    return cw, fh, top, glyphs

out = sys.stdout
out.write('// Generated by tools/emutos_fonts.py from the EmuTOS system font sources.\n')
out.write('// Font data (C) The EmuTOS development team, GPL-2.0-or-later.\n')
out.write('#include "gem/font.h"\n\nnamespace gem {\n')
names = []
for p in sys.argv[1:]:
    cw, fh, top, glyphs = parse(p)
    name = 'font_%dx%d' % (cw, fh)
    names.append(name)
    out.write('static const unsigned char %s_data[256 * %d] = {\n' % (name, fh))
    for g in glyphs:
        out.write('  ' + ','.join('0x%02x' % v for v in g) + ',\n')
    out.write('};\n')
    out.write('const SysFont %s = { %d, %d, %d, %s_data };\n\n' % (name, cw, fh, top, name))
out.write('} // namespace gem\n')
