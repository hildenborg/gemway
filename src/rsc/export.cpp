std::string fmt(const char* f, ...) __attribute__((format(printf, 1, 2)));
std::string fmt(const char* f, ...)
{
    char buf[1024];
    va_list ap;
    va_start(ap, f);
    vsnprintf(buf, sizeof buf, f, ap);
    va_end(ap);
    return buf;
}

struct Sym { std::string name; int value; std::string what; };

std::vector<Sym> collect(const Rsc& r)
{
    std::vector<Sym> v;
    std::string pre = r.prefix.empty() ? "" : r.prefix + "_";
    for (size_t t = 0; t < r.trees.size(); t++) {
        const Tree& tr = r.trees[t];
        if (!tr.name.empty())
            v.push_back({ pre + tr.name, int(t), tr.kind == TreeKind::Menu ? "MENU TREE" : "TREE" });
        for (size_t i = 0; i < tr.obj.size(); i++)
            if (!tr.obj[i].name.empty())
                v.push_back({ pre + tr.obj[i].name, int(i), fmt("OBJECT in TREE #%zu", t) });
    }
    for (size_t i = 0; i < r.strings.size(); i++)
        if (!r.strings[i].name.empty())
            v.push_back({ pre + r.strings[i].name, int(i), r.strings[i].isAlert() ? "ALERT STRING" : "FREE STRING" });
    for (size_t i = 0; i < r.images.size(); i++)
        if (!r.images[i].name.empty()) v.push_back({ pre + r.images[i].name, int(i), "FREE IMAGE" });
    return v;
}

std::string cString(const std::string& s)
{
    std::string o = "\"";
    for (unsigned char c : s) {
        if (c == '"' || c == '\\') { o += '\\'; o += char(c); }
        else if (c < 32 || c >= 127) o += fmt("\\%03o", c);
        else o += char(c);
    }
    return o + "\"";
}

const char* typeConst(int t)
{
    static char buf[16];
    const char* n = typeName(t);
    if (n[1] == '_' && t >= G_BOX && t <= G_CICON) return n;
    snprintf(buf, sizeof buf, "%d", t);
    return buf;
}

std::string flagsExpr(uint16_t f)
{
    static const char* names[] = { "SELECTABLE", "DEFAULT", "EXIT", "EDITABLE", "RBUTTON", "LASTOB",
                                   "TOUCHEXIT", "HIDETREE", "INDIRECT", "FLAGS9", "FLAGS10", "FLAGS11",
                                   "FLAGS12", "FLAGS13", "FLAGS14", "FLAGS15" };
    if (!f) return "NONE";
    std::string s;
    for (int b = 0; b < 16; b++)
        if (f & (1 << b)) { if (!s.empty()) s += "|"; s += names[b]; }
    return s;
}

std::string stateExpr(uint16_t f)
{
    static const char* names[] = { "SELECTED", "CROSSED", "CHECKED", "DISABLED", "OUTLINED", "SHADOWED",
                                   "WHITEBAK", "DRAW3D", "STATE8", "STATE9", "STATE10", "STATE11",
                                   "STATE12", "STATE13", "STATE14", "STATE15" };
    if (!f) return "NORMAL";
    std::string s;
    for (int b = 0; b < 16; b++)
        if (f & (1 << b)) { if (!s.empty()) s += "|"; s += names[b]; }
    return s;
}

std::string coord(int16_t v)
{
    if ((v & 0xFF00) == 0) return std::to_string(v & 0xFF);
    return fmt("0x%04X", uint16_t(v));
}

